const PAGE_I18N = {};

function applyLanguage(lang) {
  const dict = I18N[lang] || I18N.fr;
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  const pageDict = PAGE_I18N[lang] || {};
  document.querySelectorAll('[data-i18n-page]').forEach(function(el) {
    const key = el.getAttribute('data-i18n-page');
    if (pageDict[key] !== undefined) el.textContent = pageDict[key];
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(function(el) {
    const key = el.getAttribute('data-i18n-ph');
    if (dict[key] !== undefined) el.setAttribute('placeholder', dict[key]);
  });
  document.documentElement.setAttribute('lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  document.body.classList.toggle('rtl', lang === 'ar');
  localStorage.setItem('clicly_lang', lang);
  const currentFlag = document.getElementById('langCurrentFlag');
  const flags = { fr: '🇫🇷', en: '🇬🇧', ar: '🇸🇦', es: '🇪🇸' };
  if (currentFlag) currentFlag.textContent = flags[lang] || '🇫🇷';
}

document.addEventListener('DOMContentLoaded', function() {
  const saved = localStorage.getItem('clicly_lang') || 'fr';
  applyLanguage(saved);

  const toggle = document.getElementById('langToggle');
  const menu = document.getElementById('langMenu');
  if (toggle && menu) {
    toggle.addEventListener('click', function(e) {
      e.stopPropagation();
      menu.classList.toggle('open');
    });
    menu.querySelectorAll('[data-lang]').forEach(function(btn) {
      btn.addEventListener('click', function() {
        applyLanguage(btn.getAttribute('data-lang'));
        menu.classList.remove('open');
      });
    });
    document.addEventListener('click', function() { menu.classList.remove('open'); });
  }
});
